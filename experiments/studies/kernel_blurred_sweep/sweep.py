"""Sweep a pseudobulk method over Gaussian-blur length-scales.

Spatial autocorrelation is generated by blurring IID Gaussian noise with a
Gaussian kernel of bandwidth ``σ`` µm
(``Z'_i ∝ Σ_j Z_j exp(-‖x_i-x_j‖² / (2σ²))``).  The spec axis is
``gaussian_blur_sigma_um``.  Typical arms:

- ``configs/experiments/kernel_blurred_visium_pseudobulk_sweep.json`` —
  Visium-style circular spots (100 µm pitch, 55 µm diameter, gap cells dropped).
- ``configs/experiments/kernel_blurred_pseudobulk_sweep.json`` — full hex
  tiling at the same 100 µm pitch (every cell assigned).
"""
