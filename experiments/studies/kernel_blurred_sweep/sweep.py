REPO_ROOT = repo_root(__file__)
DEFAULT_VISIUM_SPEC = REPO_ROOT / "configs/experiments/kernel_blurred_visium_pseudobulk_sweep.json"
DEFAULT_PSEUDOBULK_SPEC = REPO_ROOT / "configs/experiments/kernel_blurred_pseudobulk_sweep.json"


@dataclass
class KernelBlurredSweepSpec:
    experiment_name: str
    base_config: Path
    output_root: Path
    alpha: float
    bandwidths_um: list[float]
    seeds: list[int]
    coordinate_um_per_unit: float | None = None

    def validate(self) -> "KernelBlurredSweepSpec":
        if not self.base_config.exists():
            raise ValueError(f"base_config missing: {self.base_config}")
        if not self.bandwidths_um:
            raise ValueError("gaussian_blur_sigma_um must be non-empty")
        if any(float(v) <= 0 for v in self.bandwidths_um):
            raise ValueError("gaussian_blur_sigma_um entries must be > 0")
        if not self.seeds:
            raise ValueError("seeds must be non-empty")
        if self.coordinate_um_per_unit is not None and float(self.coordinate_um_per_unit) <= 0:
            raise ValueError("coordinate_um_per_unit must be > 0 when provided")
        if not 0.0 < float(self.alpha) < 1.0:
            raise ValueError("alpha must lie strictly between 0 and 1")
        self.base_config = self.base_config.resolve()
        self.output_root = self.output_root.resolve()
        return self


@dataclass(frozen=True)
class DatasetKey:
    bandwidth_um: float
    data_seed: int

    @property
    def slug(self) -> str:
        return f"bw{_format_number(self.bandwidth_um)}_seed{int(self.data_seed)}"


@dataclass(frozen=True)
class KernelBlurredRunCondition:
    dataset_key: DatasetKey
    run_name: str


def _format_number(value: float) -> str:
    text = f"{float(value):.6g}"
    return text.replace("-", "m").replace(".", "p")


def _slugify_method_name(value: str) -> str:
    out = []
    for ch in str(value):
        if ch.isalnum() or ch in {"_", "-"}:
            out.append(ch.lower())
        else:
            out.append("_")
    slug = "".join(out).strip("_")
    return slug or "method"


def _load_gaussian_blur_sigmas_um(payload: dict[str, Any]) -> list[float]:
    raw = payload.get("gaussian_blur_sigma_um", payload.get("bandwidths_um"))
    if raw is None:
        raise ValueError("spec must set gaussian_blur_sigma_um (Gaussian blur σ in µm)")
    return [float(v) for v in raw]


def load_kernel_blurred_sweep_spec(path: str | Path) -> KernelBlurredSweepSpec:
    payload = load_spec(path)
    experiment_name, base_config, output_root = common_study_fields(payload)
    spec = KernelBlurredSweepSpec(
        experiment_name=experiment_name,
        base_config=base_config,
        output_root=output_root,
        alpha=float(payload.get("alpha", 0.05)),
        bandwidths_um=_load_gaussian_blur_sigmas_um(payload),
        seeds=[int(v) for v in payload["seeds"]],
        coordinate_um_per_unit=(
            float(payload["coordinate_um_per_unit"]) if "coordinate_um_per_unit" in payload else None
        ),
    )
    return spec.validate()


def analysis_dir_for_spec(spec: KernelBlurredSweepSpec) -> Path:
    return analysis_dir_for_output(spec.output_root)


def datasets_dir_for_spec(spec: KernelBlurredSweepSpec) -> Path:
    return spec.output_root / "datasets"


def runs_dir_for_spec(spec: KernelBlurredSweepSpec) -> Path:
    return runs_dir_for_output(spec.output_root)


def manifest_path_for_spec(spec: KernelBlurredSweepSpec) -> Path:
    return manifest_path_for_output(spec.output_root)


def dataset_cache_path(spec: KernelBlurredSweepSpec, key: DatasetKey) -> Path:
    return datasets_dir_for_spec(spec) / f"{key.slug}.npz"


def expand_kernel_blurred_conditions(
    spec: KernelBlurredSweepSpec, *, method_name: str
) -> list[KernelBlurredRunCondition]:
    method_slug = _slugify_method_name(method_name)
    conditions: list[KernelBlurredRunCondition] = []
    for bandwidth in spec.bandwidths_um:
        for seed in spec.seeds:
            key = DatasetKey(bandwidth_um=float(bandwidth), data_seed=int(seed))
            conditions.append(
                KernelBlurredRunCondition(
                    dataset_key=key,
                    run_name=f"{key.slug}_{method_slug}",
                )
            )
    return conditions


def _load_base_mapping(path: Path) -> dict[str, Any]:
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def _require_smooth_kernel(base_mapping: dict[str, Any]) -> None:
    kernel_payload = dict((base_mapping.get("data") or {}).get("kernel") or {})
    kernel_type = str(kernel_payload.get("type") or "")
    if kernel_type != "smooth":
        raise ValueError(
            "kernel_blurred_sweep requires data.kernel.type='smooth' "
            f"(got {kernel_type!r})"
        )


def build_data_config(base_mapping: dict[str, Any], *, key: DatasetKey) -> DataConfig:
    data_payload = copy.deepcopy(base_mapping["data"])
    data_payload["seed"] = int(key.data_seed)
    data_payload["delta"] = 0.0
    kernel_payload = dict(data_payload.get("kernel") or {})
    kernel_payload["type"] = "smooth"
    kernel_payload["distance"] = float(key.bandwidth_um)
    data_payload["kernel"] = kernel_payload
    return DataConfig(**data_payload).validate()


def _build_run_config_for_condition(
    spec: KernelBlurredSweepSpec,
    condition: KernelBlurredRunCondition,
    *,
    base_mapping: dict[str, Any],
) -> RunConfig:
    merged = copy.deepcopy(base_mapping)
    merged.setdefault("output", {})
    merged["output"]["out_dir"] = str(runs_dir_for_spec(spec))
    merged["output"]["run_name"] = condition.run_name
    merged["data"] = asdict(build_data_config(base_mapping, key=condition.dataset_key))
    merged["test"] = copy.deepcopy(base_mapping["test"])
    merged["test"]["seed"] = int(condition.dataset_key.data_seed)
    if spec.coordinate_um_per_unit is not None:
        merged["test"]["coordinate_um_per_unit"] = float(spec.coordinate_um_per_unit)
    return run_config_from_mapping(merged).validate()


def _result_json_path(spec: KernelBlurredSweepSpec, run_name: str) -> Path:
    return runs_dir_for_spec(spec) / run_name / f"{run_name}_result.json"


def ensure_dataset_cached(
    spec: KernelBlurredSweepSpec,
    key: DatasetKey,
    *,
    base_mapping: dict[str, Any],
) -> Path:
    cache_path = dataset_cache_path(spec, key)
    if cache_path.exists():
        return cache_path
    data_cfg = build_data_config(base_mapping, key=key)
    dataset = generate_synthetic_dataset(data_cfg)
    save_dataset_cache(cache_path, dataset)
    print(f"  cached dataset: {cache_path}", flush=True)
    return cache_path


def run_kernel_blurred_sweep(
    spec: KernelBlurredSweepSpec,
    *,
    spec_path: str | None = None,
    dry_run: bool = False,
    max_runs: int | None = None,
) -> dict[str, object]:
    base_mapping = _load_base_mapping(spec.base_config)
    _require_smooth_kernel(base_mapping)
    base_config = run_config_from_mapping(base_mapping).validate()
    method_name = str(base_config.test.method)
    conditions = expand_kernel_blurred_conditions(spec, method_name=method_name)
    if max_runs is not None:
        conditions = conditions[:max_runs]

    unique_keys = sorted(
        {condition.dataset_key for condition in conditions},
        key=lambda key: (key.bandwidth_um, key.data_seed),
    )

    manifest_payload: dict[str, object] = {
        "experiment_name": spec.experiment_name,
        "base_config": str(spec.base_config),
        "test_method": method_name,
        "output_root": str(spec.output_root),
        "analysis_dir": str(analysis_dir_for_spec(spec)),
        "datasets_dir": str(datasets_dir_for_spec(spec)),
        "alpha": float(spec.alpha),
        "gaussian_blur_sigma_um": list(spec.bandwidths_um),
        "bandwidths_um": list(spec.bandwidths_um),
        "seeds": list(spec.seeds),
        "coordinate_um_per_unit": (
            float(spec.coordinate_um_per_unit) if spec.coordinate_um_per_unit is not None else None
        ),
        "unique_dataset_count": len(unique_keys),
        "planned_run_count": len(conditions),
        "runs": [],
    }
    if spec_path is not None:
        manifest_payload["config_snapshot"] = build_manifest_config_snapshot(
            spec_path,
            {"base_config": spec.base_config},
        )

    if dry_run:
        manifest_payload["planned_datasets_preview"] = [key.slug for key in unique_keys[:10]]
        manifest_payload["planned_runs_preview"] = [
            {
                "run_name": condition.run_name,
                "dataset_key": condition.dataset_key.slug,
                "test_method": method_name,
                "bandwidth_um": condition.dataset_key.bandwidth_um,
            }
            for condition in conditions[:20]
        ]
        return manifest_payload

    spec.output_root.mkdir(parents=True, exist_ok=True)
    datasets_dir_for_spec(spec).mkdir(parents=True, exist_ok=True)
    runs_dir_for_spec(spec).mkdir(parents=True, exist_ok=True)
    analysis_dir_for_spec(spec).mkdir(parents=True, exist_ok=True)

    from methods.permutation import run_permutation_method

    cached_datasets: dict[str, DatasetBundle] = {}
    for key in unique_keys:
        cache_path = ensure_dataset_cached(spec, key, base_mapping=base_mapping)
        cached_datasets[key.slug] = load_dataset_cache(cache_path)

    for index, condition in enumerate(conditions, start=1):
        result_path = _result_json_path(spec, condition.run_name)
        if result_path.exists():
            print(f"[{index}/{len(conditions)}] skip existing {condition.run_name}", flush=True)
            manifest_payload["runs"].append(
                {
                    "run_name": condition.run_name,
                    "dataset_key": condition.dataset_key.slug,
                    "dataset_cache_path": str(dataset_cache_path(spec, condition.dataset_key)),
                    "bandwidth_um": float(condition.dataset_key.bandwidth_um),
                    "data_seed": int(condition.dataset_key.data_seed),
                    "test_method": method_name,
                    "result_json_path": str(result_path.resolve()),
                    "skipped": True,
                }
            )
            continue

        print(f"[{index}/{len(conditions)}] {condition.run_name}", flush=True)
        run_config = _build_run_config_for_condition(spec, condition, base_mapping=base_mapping)
        dataset = cached_datasets[condition.dataset_key.slug]
        result = run_permutation_method(dataset, run_config.test)
        _, saved_path = save_standardized_outputs(dataset, result, run_config)
        manifest_payload["runs"].append(
            {
                "run_name": condition.run_name,
                "dataset_key": condition.dataset_key.slug,
                "dataset_cache_path": str(dataset_cache_path(spec, condition.dataset_key)),
                "bandwidth_um": float(condition.dataset_key.bandwidth_um),
                "data_seed": int(condition.dataset_key.data_seed),
                "test_method": method_name,
                "p_value": float(result.p_value),
                "stat_true": float(result.stat_true),
                "result_json_path": str(saved_path.resolve()),
                "skipped": False,
            }
        )

    manifest_path = manifest_path_for_spec(spec)
    with open(manifest_path, "w", encoding="utf-8") as handle:
        json.dump(manifest_payload, handle, indent=2)
    print(f"Saved manifest to: {manifest_path}", flush=True)
    return manifest_payload


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Run the Gaussian-blurred synthetic-noise sweep (not an MSR study)."
    )
    add_spec_argument(
        parser,
        help=(
            "Sweep spec. Use "
            "configs/experiments/kernel_blurred_visium_pseudobulk_sweep.json "
            "(Visium circles), "
            "configs/experiments/kernel_blurred_pseudobulk_sweep.json "
            "(full hex tiling), or "
            "configs/experiments/kernel_blurred_variogram_gene_specific_sweep.json "
            "(variogram-matched permutations, 10 seeds at 10, 15, and 20 µm)."
        ),
    )
    add_sweep_run_arguments(parser)
    return parser


def main() -> None:
    args = _build_arg_parser().parse_args()
    spec = load_kernel_blurred_sweep_spec(args.spec)
    payload = run_kernel_blurred_sweep(
        spec,
        spec_path=args.spec,
        dry_run=args.dry_run,
        max_runs=args.max_runs,
    )
    print(json.dumps(payload, indent=2))


if __name__ == "__main__":
    main()
